"""
OpenSearch Benchmark (OSB) executor for coldbench: runs the cold and warm blocks of one JVM run through OSB itself.

OSB does not clear caches between iterations. This module writes a derived, search-only OSB workload from a coldbench
op set (the corpus' OSB workload operations plus the generated ones) with:
  - test procedure "cold": every op as its own task, `iterations: N`, `warmup-iterations: 0`, 1 client, in the run's
    seeded random order with the reference op first and last; the op type is "coldpath-search", a custom runner
    (workload.py) that, before EVERY iteration, runs the coldbench clear and verification (bufferpool clear, cache
    clear, agent drop_caches + pageout, cached_blocks == 0, residency) and then delegates to OSB's own search runner
    (osbenchmark.worker_coordinator.runner.Query: request body search, scroll-search or paginated-search). The clear
    and the counter snapshots use a separate stdlib HTTP client, never OSB's client, so OSB's service_time covers only
    the search requests (OSB times a runner from its first to its last request on its own client).
  - test procedure "warm": every op with W + M iterations, cache false, runner "coldpath-warm" = OSB's search runner
    that records the M measured iterations after W warm-up calls.
The custom runner also appends one coldbench "sample" record per iteration (took, wall around the delegated call, IO
deltas, verification) to the session's samples.jsonl, marked executor=osb, so analyze.py treats OSB and replay runs
the same way. OSB's own summary (service_time percentiles per task) is stored next to it as an "osb_summary" record.
"""
import json
import os
import shutil
import subprocess
import sys

here = os.path.dirname(os.path.abspath(__file__))

OSB_TYPE = {"search": "search", "scroll": "scroll-search", "search_after": "paginated-search"}

WORKLOAD_PY = r'''
# Generated by coldbench osb_cold.py: the coldpath-search runner (cold iteration = clear, verify, then OSB's Query).
import asyncio, json, os, sys, time

_cfg = json.load(open(os.environ["COLDPATH_OSB_CONFIG"]))
sys.path.insert(0, _cfg["harness_dir"])
import coldbench  # noqa: E402
from common import JsonlWriter  # noqa: E402
from osbenchmark.worker_coordinator.runner import Query  # noqa: E402


class _State:
    def __init__(self):
        c = _cfg
        token = open(c["token_file"]).read().strip() if c.get("token_file") else ""
        self.node = coldbench.Node(c["url"], c.get("agent"), token, c["residency_tolerance"])
        self.it = coldbench.Iteration(self.node, c["arm"], c["uuids"], c["residency_every"])
        self.w = JsonlWriter(c["samples_path"])
        self.counts = {}


_state = None


def _st():
    global _state
    if _state is None:
        _state = _State()
    return _state


class ColdSearch:
    def __init__(self):
        self.query = Query()

    async def __call__(self, es, params):
        st = _st()
        loop = asyncio.get_running_loop()
        pre_state, pre, trace = await loop.run_in_executor(None, self._before)
        inner = dict(params)
        inner["operation-type"] = params["coldpath-osb-type"]
        t = time.perf_counter()
        result = await self.query(es, inner)
        wall = (time.perf_counter() - t) * 1e3
        await loop.run_in_executor(None, self._after, params, pre_state, pre, trace, result, wall)
        return result

    def _before(self):
        st = _st()
        pre_state = st.it.clear()
        trace = _cfg.get("read_size_trace") if st.node.agent is not None else None
        if trace:
            st.node.agent.request("POST", f"/trace/{trace}/_start?arm={_cfg['arm']['node']}")
        return pre_state, st.it.snapshot(), trace

    def _after(self, params, pre_state, pre, trace, result, wall):
        st = _st()
        idle_ms, _ = st.node.wait_prefetch_idle()
        post = st.it.snapshot()
        io = coldbench.io_delta(pre, post)
        if trace:
            io["nfs_read_sizes" if trace == "nfs" else "block_read_sizes"] = st.node.agent.request(
                "POST", f"/trace/{trace}/_stop?arm={_cfg['arm']['node']}")
        ok, checks = st.it.verify(pre_state, io)
        op = params["coldpath-op"]
        key = ("cold", op, params["coldpath-pos"])
        i = st.counts.get(key, 0)
        st.counts[key] = i + 1
        st.w.write({"schema": coldbench.SCHEMA, "t": time.time(), "type": "sample", "mode": "cold", "executor": "osb",
                    **_cfg["run"], "pos": params["coldpath-pos"], "op": op, "iter": i, "took_ms": result.get("took"),
                    "wall_ms": wall, "requests": result.get("pages", 1), "cold_ok": ok, "checks": checks,
                    "clear": pre_state, "io": io, "post_idle_ms": idle_ms, "osb_meta": {k: result.get(k) for k in
                    ("hits", "hits_relation", "timed_out", "pages")}})
        if not ok and _cfg.get("strict"):
            raise RuntimeError(f"cold verification failed: {op} iter {i}: {checks}")


class WarmSearch:
    """OSB's Query with caches kept; records the measured iterations (after coldpath-warmup warm-up calls)."""

    def __init__(self):
        self.query = Query()

    async def __call__(self, es, params):
        st = _st()
        loop = asyncio.get_running_loop()
        op = params["coldpath-op"]
        key = ("warm", op, params["coldpath-pos"])  # the reference op runs twice (first and last position)
        n = st.counts.get(key, 0)
        st.counts[key] = n + 1
        measured = n >= params["coldpath-warmup"]
        pre = await loop.run_in_executor(None, st.it.snapshot) if measured else None
        inner = dict(params)
        inner["operation-type"] = params["coldpath-osb-type"]
        t = time.perf_counter()
        result = await self.query(es, inner)
        wall = (time.perf_counter() - t) * 1e3
        if measured:
            await loop.run_in_executor(None, self._after, params, op, n - params["coldpath-warmup"], pre, result, wall)
        return result

    def _after(self, params, op, i, pre, result, wall):
        st = _st()
        idle_ms, _ = st.node.wait_prefetch_idle()
        io = coldbench.io_delta(pre, st.it.snapshot())
        st.w.write({"schema": coldbench.SCHEMA, "t": time.time(), "type": "sample", "mode": "warm", "executor": "osb",
                    **_cfg["run"], "pos": params["coldpath-pos"], "op": op, "iter": i, "took_ms": result.get("took"),
                    "wall_ms": wall, "requests": result.get("pages", 1), "io": io, "post_idle_ms": idle_ms})


def register(registry):
    registry.register_runner("coldpath-search", ColdSearch(), async_runner=True)
    registry.register_runner("coldpath-warm", WarmSearch(), async_runner=True)
'''


def _osb_op(op, index, cold, pos, warmup):
    typ = op.get("type", "search")
    o = {"name": f"{op['name']}#{pos}", "index": index, "body": op["body"], "cache": False, "detailed-results": True,
         "request-params": {k: v for k, v in op.get("params", {}).items() if k != "request_cache"}}
    if typ in ("scroll", "search_after"):
        o["pages"] = op.get("pages", 10)
        o["results-per-page"] = op.get("page_size", op["body"].get("size", 10))
    o["operation-type"] = "coldpath-search" if cold else "coldpath-warm"
    o["coldpath-osb-type"] = OSB_TYPE[typ]
    o["coldpath-op"] = op["name"]
    o["coldpath-pos"] = pos
    o["coldpath-warmup"] = 0 if cold else warmup
    return o


def write_workload(path, ordered_ops, index, mode, iters, warmup):
    """ordered_ops: the run's op order (reference first and last). One OSB operation and task per position."""
    if os.path.exists(path):
        shutil.rmtree(path)
    os.makedirs(path)
    cold = mode == "cold"
    ops = [_osb_op(op, index, cold, pos, warmup) for pos, op in enumerate(ordered_ops)]
    # warm-up iterations are run as OSB iterations too, so the runner knows which calls are warm-up (it records only
    # the measured ones); OSB's own summary then includes them, the samples do not
    schedule = [{"operation": o["name"], "clients": 1, "warmup-iterations": 0, "iterations": iters + (0 if cold else warmup)}
                for o in ops]
    wl = {"version": 2, "description": f"coldbench derived search-only workload ({mode})",
          "operations": ops, "test_procedures": [{"name": mode, "default": True, "schedule": schedule}]}
    with open(os.path.join(path, "workload.json"), "w") as f:
        json.dump(wl, f, indent=1)
    with open(os.path.join(path, "workload.py"), "w") as f:
        f.write(WORKLOAD_PY)
    return path


def osb_subcommand(osb_bin):
    out = subprocess.run([osb_bin, "--help"], capture_output=True, text=True).stdout
    return "execute-test" if "execute-test" in out else "run"


def run_block(session, it, run, index, mode, ordered_ops, iters, warmup=0):
    """Runs one cold or warm block of one JVM run through OSB. Raises on an OSB failure."""
    a = session.a
    base = os.path.join(a.out, "osb", f"{run['run_id'].replace('#', '_')}-{mode}")
    wl = write_workload(os.path.join(base, "workload"), ordered_ops, index, mode, iters, warmup)
    cfg = {"harness_dir": here, "url": a.url, "agent": a.agent, "token_file": a.token_file, "arm": it.arm,
           "uuids": it.uuids, "residency_every": a.residency_every, "residency_tolerance": a.residency_tolerance,
           "samples_path": os.path.join(a.out, "samples.jsonl"), "run": run, "strict": a.strict,
           "read_size_trace": getattr(session, "read_trace_kind", None)}
    cfg_path = os.path.join(base, "coldpath-osb.json")
    with open(cfg_path, "w") as f:
        json.dump(cfg, f)
    results = os.path.join(base, "results.json")
    host = a.url.split("://", 1)[1].rstrip("/")
    cmd = [a.osb_bin, osb_subcommand(a.osb_bin), "--pipeline=benchmark-only", f"--workload-path={wl}",
           f"--test-procedure={mode}", f"--target-hosts={host}", "--kill-running-processes", "--on-error=abort",
           f"--results-file={results}", "--results-format=csv", f"--user-tag=coldbench_run:{run['run_id']},mode:{mode}"]
    if a.url.startswith("https"):
        cmd.append("--client-options=use_ssl:true,verify_certs:false")
    session.log("  osb: " + " ".join(cmd))
    p = subprocess.run(cmd, env={**os.environ, "COLDPATH_OSB_CONFIG": cfg_path}, capture_output=True, text=True)
    with open(os.path.join(base, "osb.log"), "w") as f:
        f.write(p.stdout + "\n" + p.stderr)
    if p.returncode != 0 or "[ERROR]" in p.stdout:
        raise RuntimeError(f"OSB {mode} block of {run['run_id']} failed (rc {p.returncode}); see {base}/osb.log:\n"
                           + (p.stdout + p.stderr)[-3000:])
    summary = open(results).read() if os.path.exists(results) else None
    session.record(type="osb_summary", **run, mode=mode, osb_cmd=cmd, results_csv=summary)
    return summary


if __name__ == "__main__":
    sys.exit("osb_cold.py is used by coldbench.py run --executor osb")
